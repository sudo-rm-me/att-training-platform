export const MESSAGES: Record<Locale, DeepPartial<Messages>> = { en, fr, de, es };

type Join<K, P> = K extends string ? (P extends string ? `${K}.${P}` : never) : never;
export type MessageKey = { [S in keyof Messages]: Join<S, keyof Messages[S]> }[keyof Messages];

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

/** Best supported locale from an Accept-Language header. */
export function negotiate(header: string | null | undefined): Locale {
  if (!header) return DEFAULT_LOCALE;
  const wanted = header
    .split(",")
    .map((part) => {
      const [tag, q] = part.trim().split(";q=");
      return { lang: tag.toLowerCase().split("-")[0], q: q ? Number(q) : 1 };
    })
    .sort((a, b) => b.q - a.q);
  return wanted.find((w) => isLocale(w.lang))?.lang as Locale | undefined ?? DEFAULT_LOCALE;
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const own = MESSAGES[locale] as Record<string, Record<string, string> | undefined>;
  const base = en as unknown as Record<string, Record<string, string>>;
  return (key, vars) => {
    const [section, name] = key.split(".");
    let s = own[section]?.[name] ?? base[section]?.[name] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
